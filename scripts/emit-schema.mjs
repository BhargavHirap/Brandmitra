/**
 * Exports the database schema to a plain .sql file.
 *
 * The app applies the schema automatically on first use, so you only need this
 * when you want to build the production database by hand:
 *
 *   npm run db:sql
 *   npx wrangler d1 execute brandmitra --remote --file=./db/brandmitra.sql
 *
 * The SQL is read from src/db/schema.ts, the same file the app uses, so the
 * exported .sql file can never drift away from the real schema.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = join(here, "..", "src", "db", "schema.ts");
const outputDirectory = join(here, "..", "db");
const outputFile = join(outputDirectory, "brandmitra.sql");

const source = readFileSync(schemaPath, "utf8");

/** Pull the text between a start marker and an end marker. */
function extract(startMarker, endMarker) {
  const start = source.indexOf(startMarker);
  if (start === -1) throw new Error(`Could not find "${startMarker}" in src/db/schema.ts`);
  const from = start + startMarker.length;
  const end = source.indexOf(endMarker, from);
  if (end === -1) throw new Error(`Could not find the end of "${startMarker}"`);
  return source.slice(from, end).trim();
}

const schemaSql = extract("export const SCHEMA_SQL = `", "`;\n\nexport const SEED_SQL = `");
const seedSql = extract("export const SEED_SQL = `", "`;\n");

const header = `-- Brandmitra database schema (generated by scripts/emit-schema.mjs)
-- Safe to run more than once: every statement is idempotent.
-- Generated: ${new Date().toISOString()}

`;

mkdirSync(outputDirectory, { recursive: true });
writeFileSync(outputFile, `${header}${schemaSql}\n\n${seedSql}\n`, "utf8");

const tableCount = (schemaSql.match(/CREATE TABLE/g) ?? []).length;
console.log(`Wrote ${outputFile} (${tableCount} tables + plan seed data).`);
